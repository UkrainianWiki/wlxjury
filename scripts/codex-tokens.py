#!/usr/bin/env python3
"""Builds public/stylesheets/vendor/codex/codex-tokens.css from the two vendored Codex files.

The vendored files (theme-wikimedia-ui-root.css, theme-wikimedia-ui-mode-dark.css) are the
unmodified npm files; both put their tokens on :root. The app picks the colour mode with
data-bs-theme on <html>, so this script copies each file's body unchanged under the selector
for its mode. Run with --check to fail when the generated file is out of date, or when one of
codex-theme.css's rgb() companions (a `--name-rgb: r, g, b; /* = --token */` line) differs from
the vendored value of its token in its rule's mode (a rule for [data-bs-theme=dark] the dark
value, one for :root or [data-bs-theme=light] the light one, a rule for both each).
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / "public/stylesheets/vendor/codex"
OUT = D / "codex-tokens.css"
THEME = ROOT / "public/stylesheets/codex-theme.css"


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def scoped(name, selector):
    text = read(D / name)
    assert text.count("\n:root {") == 1, name
    return text.replace("\n:root {", "\n" + selector + " {")


def build():
    return ("/* Generated by scripts/codex-tokens.py from the files next to it; do not edit.\n"
            "   Only the :root selector of each file is replaced (see docs/vendor/codex.md). */\n\n"
            + scoped("theme-wikimedia-ui-root.css", ":root, [data-bs-theme=light]")
            + "\n"
            + scoped("theme-wikimedia-ui-mode-dark.css", "[data-bs-theme=dark]"))


def tokens(name):
    """The file's tokens, name -> value, a var() reference resolved within the file."""
    found = dict(re.findall(r"^\s*(--[\w-]+):\s*([^;]+);", read(D / name), re.M))
    return found


def rgb(name, values, light=None):
    """A token's colour as (r, g, b), following var() references (the dark file falls back to
    the light one for a token it doesn't change)."""
    value = values.get(name, (light or {}).get(name))
    if value is None:
        raise KeyError(name)
    value = value.strip()
    ref = re.fullmatch(r"var\(\s*(--[\w-]+)\s*\)", value)
    if ref:
        return rgb(ref.group(1), values, light)
    hexa = re.fullmatch(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})", value)
    if not hexa:
        raise ValueError(f"{name}: {value} is not a hex colour")
    h = hexa.group(1)
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def companion_errors():
    """codex-theme.css's rgb() companions that differ from their tokens, or name none."""
    light = tokens("theme-wikimedia-ui-root.css")
    dark = tokens("theme-wikimedia-ui-mode-dark.css")
    text = re.sub(r"\r\n", "\n", read(THEME))
    errors, checked = [], 0
    for decl in re.finditer(r"(--[\w-]+-rgb):\s*([^;]*);([^\n]*)", text):
        name, value, rest = decl.groups()
        selector = text[text.rfind("}", 0, decl.start()) + 1:text.rfind("{", 0, decl.start())]
        selector = re.sub(r"/\*.*?\*/", "", selector, flags=re.S).strip()
        token = re.match(r"\s*/\*\s*=\s*(--[\w-]+)\s*\*/", rest)
        if not token:
            errors.append(f"{name} in '{selector}' names no token (/* = --token */)")
            continue
        modes = []
        if re.search(r":root|\[data-bs-theme=light\]", selector):
            modes.append(("light", light, None))
        if "[data-bs-theme=dark]" in selector:
            modes.append(("dark", dark, light))
        if not modes:
            errors.append(f"{name} in '{selector}': no mode")
        have = tuple(int(v) for v in re.findall(r"\d+", value))
        for mode, values, fallback in modes:
            want = rgb(token.group(1), values, fallback)
            checked += 1
            if have != want:
                errors.append(f"{name} in '{selector}' ({mode}): {', '.join(map(str, have))}, "
                              f"but {token.group(1)} is {', '.join(map(str, want))}")
    if checked == 0:
        errors.append("no rgb() companions found in codex-theme.css")
    return errors


if __name__ == "__main__":
    out = build()
    if "--check" in sys.argv:
        problems = [] if read(OUT) == out else ["codex-tokens.css is out of date"]
        problems += companion_errors()
        sys.exit("\n".join(problems) if problems else 0)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
